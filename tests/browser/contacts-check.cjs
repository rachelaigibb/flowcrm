const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
(async()=>{
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4174/contacts.html');await page.waitForLoadState('networkidle');
const names=()=>page.locator('tbody tr td:nth-child(2)').allTextContents();
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
assert((await names())[0]==='Zulu Fixture','default entry order');
await page.getByRole('button',{name:'Name',exact:true}).click();assert((await names())[0]==='Alpha Fixture','ascending');
await page.getByRole('button',{name:'Name',exact:true}).click();assert((await names())[1]==='Middle Fixture','descending');
await page.getByRole('button',{name:'Name',exact:true}).click();assert((await names())[1]==='Alpha Fixture','off restores entry order');
const handle=page.getByRole('separator',{name:'Resize Name column'});
const before=await page.getByRole('columnheader').nth(1).boundingBox();const box=await handle.boundingBox();
await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+126,box.y+box.height/2,{steps:8});await page.mouse.up();
const after=await page.getByRole('columnheader').nth(1).boundingBox();
assert(after.width>before.width+100,'actual column grows from drag');
assert((await names())[0]==='Zulu Fixture','resizing does not sort');
await handle.focus();await page.keyboard.press('ArrowLeft');assert(Number(await handle.getAttribute('aria-valuenow'))<after.width,'keyboard resize');
await page.getByRole('button',{name:'Filter by tags'}).click();await page.getByRole('checkbox',{name:'Buyer',exact:true}).check();
assert((await names()).length===2,'tag filter');
await page.keyboard.press('Escape');await page.getByRole('button',{name:'Name',exact:true}).click();assert((await names())[0]==='Alpha Fixture','sort filtered rows');
await page.getByRole('button',{name:'Clear sort'}).click();assert((await names())[0]==='Zulu Fixture','clear sort with filter');
await page.screenshot({path:'/tmp/flowcrm-columns-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
const overflow=await page.locator('[data-slot="table-container"]').evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth}));
assert(overflow.scroll>overflow.width,'mobile horizontal scroll');
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'no document overflow');
await page.getByRole('button',{name:'Created',exact:true}).scrollIntoViewIfNeeded();await page.getByRole('button',{name:'Created',exact:true}).click();
await page.screenshot({path:'/tmp/flowcrm-columns-mobile.png',fullPage:true});
assert(errors.length===0,errors.join('\n'));console.log('PASS: browser drag, keyboard resizing, sort cycle/off, filters, desktop/mobile scroll; no page errors');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
