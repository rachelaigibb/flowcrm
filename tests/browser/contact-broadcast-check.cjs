const {chromium}=require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const assert=(ok,message)=>{if(!ok)throw new Error(message)};
 await page.goto('http://127.0.0.1:4174/contacts.html');await page.waitForLoadState('networkidle');
 await page.getByRole('button',{name:'Filter by tags'}).click();await page.getByRole('checkbox',{name:'Buyer',exact:true}).check();await page.keyboard.press('Escape');
 await page.getByRole('checkbox',{name:'Select Zulu Fixture'}).check();await page.getByRole('checkbox',{name:'Select Alpha Fixture'}).check();
 assert(await page.getByText('2 selected',{exact:true}).count()===1,'two picks from filtered list');
 await page.getByRole('button',{name:'Add to broadcast',exact:true}).click();
 await page.getByLabel('Broadcast name').fill('Synthetic new selection');
 await page.getByRole('button',{name:'Preview audience',exact:true}).click();
 await page.getByLabel('Audience preview').waitFor();
 assert(await page.getByText('2 to add · 0 already included · 0 excluded').count()===1,'new preview');
 assert(await page.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth && el.scrollLeft===0),'desktop dialog content fits');
 await page.screenshot({path:'/tmp/flowcrm-add-broadcast-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Create draft with contacts',exact:true}).click();
 await page.getByText('/broadcasts/fixture-new',{exact:true}).waitFor();
 const created=JSON.parse(await page.locator('#fixture-confirmation').innerText());assert(created.ids.join(',')==='0,1','only checked contacts');assert(created.target.kind==='new','new draft target');
 await page.getByRole('checkbox',{name:'Select Zulu Fixture'}).check();await page.getByRole('checkbox',{name:'Select Alpha Fixture'}).check();
 await page.getByRole('button',{name:'Add to broadcast',exact:true}).click();
 await page.getByLabel('Broadcast destination').selectOption('scheduled');
 await page.getByRole('button',{name:'Preview audience',exact:true}).click();await page.getByLabel('Audience preview').waitFor();
 assert(await page.getByText('1 to add · 1 already included · 0 excluded').count()===1,'scheduled duplicate preview');
 assert((await page.getByText(/Schedule stays unchanged:/).innerText()).includes('12:00:00'),'workspace scheduled time');
 await page.setViewportSize({width:390,height:844});
 const dialog=await page.getByRole('dialog').boundingBox();assert(dialog.width<=390,'dialog fits phone');
 assert(await page.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth && el.scrollLeft===0),'mobile dialog content fits');
 await page.screenshot({path:'/tmp/flowcrm-add-broadcast-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Add contacts',exact:true}).click();await page.getByText('/broadcasts/scheduled',{exact:true}).waitFor();
 const changed=JSON.parse(await page.locator('#fixture-confirmation').innerText());assert(changed.target.id==='scheduled','selected scheduled destination');
 assert(errors.length===0,errors.join('\n'));console.log('PASS: filtered contact selection, new draft confirmation, scheduled duplicate/count/time preview, exact IDs, desktop/mobile dialog; isolated mocked actions, no production changes');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
