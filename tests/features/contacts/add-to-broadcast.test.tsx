import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { beforeEach, expect, it, vi } from 'vitest'
const mocks=vi.hoisted(()=>({list:vi.fn(),preview:vi.fn(),add:vi.fn(),push:vi.fn(),refresh:vi.fn()}))
vi.mock('next/navigation',()=>({useRouter:()=>({push:mocks.push,refresh:mocks.refresh})}))
vi.mock('@/features/broadcasts/contact-audience-actions',()=>({getEditableBroadcasts:mocks.list,previewContactAudience:mocks.preview,addContactsToBroadcast:mocks.add}))
import { AddToBroadcastDialog } from '@/features/contacts/components/add-to-broadcast-dialog'
const summary={token:'reviewed',name:'Campaign',channel:'email' as const,scheduledAt:null,added:1,alreadyIncluded:1,excluded:[{name:'Unsubscribed Contact',reason:'Marketing consent required'}],total:3}
beforeEach(()=>{
 vi.clearAllMocks()
 mocks.list.mockResolvedValue({data:[{id:'draft',name:'Existing draft',channel:'email',status:'draft',scheduled_at:null},{id:'scheduled',name:'Scheduled campaign',channel:'email',status:'scheduled',scheduled_at:'2026-12-01T20:00:00Z'}]})
 mocks.preview.mockResolvedValue({data:summary});mocks.add.mockResolvedValue({data:{id:'created',added:1}})
})
it('creates a new draft only after a matching preview is confirmed',async()=>{
 const added=vi.fn(),close=vi.fn()
 await act(async()=>{render(<AddToBroadcastDialog ids={['one','two','three']} onAdded={added} onClose={close}/>)})
 expect(screen.getByRole('button',{name:'Create draft with contacts'})).toBeDisabled()
 fireEvent.change(screen.getByLabelText('Broadcast name'),{target:{value:'Picked contacts'}})
 fireEvent.click(screen.getByRole('button',{name:'Preview audience'}))
 await screen.findByLabelText('Audience preview')
 expect(screen.getByText('1 to add · 1 already included · 1 excluded')).toBeInTheDocument()
 fireEvent.click(screen.getByRole('button',{name:'Create draft with contacts'}))
 await waitFor(()=>expect(mocks.add).toHaveBeenCalledWith(['one','two','three'],expect.objectContaining({kind:'new',name:'Picked contacts',channel:'email'}),'reviewed'))
 expect(added).toHaveBeenCalledOnce();expect(close).toHaveBeenCalledOnce();expect(mocks.push).toHaveBeenCalledWith('/broadcasts/created')
})
it('shows a scheduled time in the workspace timezone and preserves the existing destination',async()=>{
 mocks.preview.mockResolvedValue({data:{...summary,scheduledAt:'2026-12-01T20:00:00Z'}})
 await act(async()=>{render(<AddToBroadcastDialog ids={['one']} timezone="America/Vancouver" onAdded={()=>{}} onClose={()=>{}}/>)})
 fireEvent.change(screen.getByLabelText('Broadcast destination'),{target:{value:'scheduled'}})
 fireEvent.click(screen.getByRole('button',{name:'Preview audience'}))
 await screen.findByLabelText('Audience preview')
 expect(screen.getByText(/Schedule stays unchanged:.*12:00:00/)).toBeInTheDocument()
 fireEvent.click(screen.getByRole('button',{name:'Add contacts'}))
 await waitFor(()=>expect(mocks.add).toHaveBeenCalledWith(['one'],{kind:'existing',id:'scheduled'},'reviewed'))
})
it('invalidates preview when the target changes and requires review again after a conflict',async()=>{
 await act(async()=>{render(<AddToBroadcastDialog ids={['one']} onAdded={()=>{}} onClose={()=>{}}/>)})
 fireEvent.change(screen.getByLabelText('Broadcast destination'),{target:{value:'draft'}})
 fireEvent.click(screen.getByRole('button',{name:'Preview audience'}))
 await screen.findByLabelText('Audience preview')
 fireEvent.change(screen.getByLabelText('Broadcast destination'),{target:{value:'scheduled'}})
 expect(screen.getByRole('button',{name:'Add contacts'})).toBeDisabled()
 fireEvent.click(screen.getByRole('button',{name:'Preview audience'}))
 await screen.findByLabelText('Audience preview')
 mocks.add.mockResolvedValue({error:'Broadcast started sending'})
 fireEvent.click(screen.getByRole('button',{name:'Add contacts'}))
 await screen.findByRole('alert')
 expect(screen.getByRole('button',{name:'Add contacts'})).toBeDisabled()
})
it('does not allow an all-excluded or already-included selection to be added',async()=>{
 mocks.preview.mockResolvedValue({data:{...summary,added:0}})
 await act(async()=>{render(<AddToBroadcastDialog ids={['one']} onAdded={()=>{}} onClose={()=>{}}/>)})
 fireEvent.change(screen.getByLabelText('Broadcast destination'),{target:{value:'draft'}})
 fireEvent.click(screen.getByRole('button',{name:'Preview audience'}))
 await screen.findByLabelText('Audience preview')
 expect(screen.getByRole('button',{name:'Add contacts'})).toBeDisabled()
 expect(mocks.add).not.toHaveBeenCalled()
})
